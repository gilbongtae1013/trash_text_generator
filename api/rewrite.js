"수업이 끝나서 나는 수업이 끝난 다음에 버스를 기다리러 갔고, 그래서 버스를 기다렸는데 버스는 바로 오지 않아서 기다리고 있었고, 그런데 기다리다 보니까 계속 기다리고 있었고 그래서 결국 버스가 올 때까지 버스를 기다리는 상태로 있었다."

